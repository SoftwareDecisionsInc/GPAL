        /// <summary>
        /// Reads user.js into a name to value dictionary, values kept exactly as written.
        /// </summary>
        /// <param name="userJsPath">Path to the user.js</param>
        /// <returns>What the file declares, empty when there is no file</returns>
        private static Dictionary<string, string> ReadUserJs(string userJsPath)
        {
            Dictionary<string, string> retVal = new Dictionary<string, string>();

            if (true == File.Exists(userJsPath))
                foreach (string line in File.ReadAllLines(userJsPath))
                {
                    Match match = Regex.Match(line, @"user_pref\(""([^""]+)"",\s*(.+)\);");

                    if (true == match.Success)
                        retVal[match.Groups[1].Value] = match.Groups[2].Value.Trim();
                }

            return retVal;
        }

        /// <summary>
        /// Writes user.js, one user_pref line per preference, sorted by name so the output is stable.
        /// </summary>
        /// <param name="userJsPath">Path to the user.js</param>
        /// <param name="preferences">What the file should declare</param>
        private static void WriteUserJs(string userJsPath, Dictionary<string, string> preferences)
        {
            StringBuilder builder = new StringBuilder();

            foreach (KeyValuePair<string, string> preference in preferences.OrderBy(p => p.Key, StringComparer.Ordinal))
                builder.AppendLine($"user_pref(\"{preference.Key}\", {preference.Value});");

            File.WriteAllText(userJsPath, builder.ToString());
        }

        /// <summary>
        /// Quotes a string the way a user.js value is written, backslashes and all.
        /// </summary>
        /// <param name="value">The value to quote</param>
        /// <returns>The value as it appears in the file</returns>
        private static string AsJsString(string value)
        {
            string retVal = $"\"{value?.Replace("\\", "\\\\").Replace("\"", "\\\"")}\"";

            return retVal;
        }

        /// <summary>
        /// Writes GPAL's preferences into a Firefox profile's user.js.<br/>
        /// Every GPAL preference is written to match the workflow, not only when missing, so a stale value from an
        /// earlier run (such as pdfjs.disabled) is corrected. Other preferences are untouched. A supplied profile is
        /// put back by <see cref="RestoreProfile"/>.
        /// </summary>
        /// <param name="profilePath">The profile to write to</param>
        /// <param name="browserSettings">Settings the preferences are taken from</param>
        public static void CreateUserJs(string profilePath, BrowserSettings browserSettings)
        {
            string userJsPath = Path.Combine(profilePath, "user.js");

            try
            {
                Dictionary<string, string> preferences = ReadUserJs(userJsPath);

                // pdfjs is Firefox's built in pdf viewer; when on, a pdf is displayed and no download starts.
                // Headless always turns it off: Get() sets OpenPDFExternally false for headless, which would
                // otherwise turn it back on. Chrome needs no rule; headless Chrome cannot display a pdf, but
                // Firefox's viewer works headless.
                preferences["pdfjs.disabled"] = browserSettings.OpenPDFExternally || browserSettings.UseHeadless ? "true" : "false";

                // false is firefox for "ask where to save every file", which is the save dialog
                preferences["browser.download.useDownloadDir"] = browserSettings.PromptForDownload ? "false" : "true";
                preferences["browser.helperApps.neverAsk.saveToDisk"] = true == browserSettings.PromptForDownload
                                                                      ? AsJsString("")
                                                                      : AsJsString(GPAL.GPALSettings.FirefoxDirectDownloadMimeTypes);

                preferences["permissions.default.image"] = browserSettings.LoadImages ? "1" : "0";
                // Maximum popups one event may open: 0 blocks, 20 is the Firefox default.
                preferences["dom.popup_maximum"] = browserSettings.BlockPopUps ? "0" : "20";
                preferences["browser.safebrowsing.enabled"] = "false";

                // browser.startup.page 0 opens blank and resume_from_crash false drops the crash restore prompt, so
                // a workflow starts where it navigates. Set both explicitly; geckodriver may leave them on a profile
                // it drove, but that cannot be relied on.
                preferences["browser.startup.page"] = "0";
                preferences["browser.sessionstore.resume_from_crash"] = "false";

                // enable and allow unsigned extensions - we will load magic off disk
                preferences["extensions.enabled"] = "true";
                preferences["xpinstall.signatures.required"] = "false";
                preferences["dom.webdriver.enabled"] = "false";

                if (false == string.IsNullOrEmpty(browserSettings.DownloadLocation))
                {
                    preferences["browser.download.dir"] = AsJsString(browserSettings.DownloadLocation);
                    preferences["browser.download.folderList"] = "2";   // 2: use the custom download directory
                }
                else
                {
                    // No download directory requested, so remove one left by an earlier run and let the profile use
                    // its own.
                    preferences.Remove("browser.download.dir");
                    preferences.Remove("browser.download.folderList");
                }

                WriteUserJs(userJsPath, preferences);
            }
            catch (Exception ex)
            {
                GPAL.PublishSimpleEvent(GPALEventType.EXCEPTION, $"Could not write preferences into [{userJsPath}]", null, GPALObjectType.None, ex);
            }
        }

        // Written into a supplied profile while GPAL runs on it and deleted once the profile is put back. One left
        // behind means a run was killed before Close, and the next launch on that profile restores from it first.
        private const string RestoreFileName = "gpal.restore.json";

        /// <summary>
        /// Takes what a supplied profile holds before Firefox is launched on it, and saves it in the profile for
        /// <see cref="RestoreProfile"/>. A snapshot an earlier run left behind is restored from first.
        /// </summary>
        /// <param name="profilePath">The profile Firefox is about to run on</param>
        /// <returns>The snapshot, or null when the profile could not be read</returns>
        public static FirefoxProfileSnapshot TakeSnapshot(string profilePath)
        {
            FirefoxProfileSnapshot retVal = null;
            string restorePath = Path.Combine(profilePath, RestoreFileName);

            try
            {
                if (true == File.Exists(restorePath))
                {
                    FirefoxProfileSnapshot leftBehind = Newtonsoft.Json.JsonConvert.DeserializeObject<FirefoxProfileSnapshot>(File.ReadAllText(restorePath));

                    leftBehind.ProfilePath = profilePath;
                    RestoreProfile(leftBehind);

                    GPAL.PublishSimpleEvent(GPALEventType.NOTICE, $"Put back the preferences an earlier run left in [{profilePath}]", null, GPALObjectType.None);
                }

                retVal = new FirefoxProfileSnapshot
                {
                    ProfilePath = profilePath,
                    UserJsBefore = ReadUserJs(Path.Combine(profilePath, "user.js")),
                    PrefsJsBefore = ReadUserJs(Path.Combine(profilePath, "prefs.js")),
                };

                File.WriteAllText(restorePath, Newtonsoft.Json.JsonConvert.SerializeObject(retVal));
            }
            catch (Exception ex)
            {
                GPAL.PublishSimpleEvent(GPALEventType.EXCEPTION, $"Could not read the preferences in [{profilePath}]", null, GPALObjectType.None, ex);
            }

            return retVal;
        }

        // Preferences a profile keeps after a run. OttoMagic is unsigned, and Firefox disables it on any start with
        // signatures required, including a person opening the profile by hand.
        private static readonly HashSet<string> KeptAfterRun = new HashSet<string> { "xpinstall.signatures.required" };

        /// <summary>
        /// Records the user.js preferences written for this run, with the values written: every one new or changed
        /// since the snapshot, by GPAL or by geckodriver. Call it once they are in place and before the browser
        /// closes; geckodriver puts user.js back when its session ends, which would hide them.
        /// </summary>
        /// <param name="snapshot">What <see cref="TakeSnapshot"/> answered</param>
        public static void NoteWrittenPreferences(FirefoxProfileSnapshot snapshot)
        {
            if (null != snapshot)
            {
                try
                {
                    foreach (KeyValuePair<string, string> preference in ReadUserJs(Path.Combine(snapshot.ProfilePath, "user.js")))
                        if ((false == snapshot.UserJsBefore.TryGetValue(preference.Key, out string was) || was != preference.Value)
                            && false == KeptAfterRun.Contains(preference.Key))
                            snapshot.Written[preference.Key] = preference.Value;

                    File.WriteAllText(Path.Combine(snapshot.ProfilePath, RestoreFileName), Newtonsoft.Json.JsonConvert.SerializeObject(snapshot));
                }
                catch (Exception ex)
                {
                    GPAL.PublishSimpleEvent(GPALEventType.EXCEPTION, $"Could not record the preferences written to [{snapshot.ProfilePath}]", null, GPALObjectType.None, ex);
                }
            }
        }

        /// <summary>
        /// Puts a supplied profile back the way <see cref="TakeSnapshot"/> found it, so the workflow's download
        /// directory, pdf handling and geckodriver's automation preferences do not stay in it.<br/>
        /// Firefox saves every user.js preference into prefs.js as it shuts down, so both files are put back, and
        /// this has to run once the browser is gone. In user.js only preferences written for the run, and still
        /// holding the value written, go back. prefs.js goes back to how it was before the run.<br/>
        /// geckodriver's own backups of user.js, which a killed run leaves behind, are removed too.
        /// </summary>
        /// <param name="snapshot">What <see cref="TakeSnapshot"/> answered</param>
        public static void RestoreProfile(FirefoxProfileSnapshot snapshot)
        {
            if (null != snapshot)
            {
                try
                {
                    PutBack(Path.Combine(snapshot.ProfilePath, "user.js"), snapshot.Written, snapshot.UserJsBefore);
                    RollBack(Path.Combine(snapshot.ProfilePath, "prefs.js"), snapshot.PrefsJsBefore);

                    // geckodriver backs up user.js on every session and only removes the backup when the session
                    // ends cleanly. The snapshot has put user.js back, so the backups a killed run left are junk.
                    foreach (string backup in Directory.GetFiles(snapshot.ProfilePath, "user.geckodriver_backup*"))
                        File.Delete(backup);

                    File.Delete(Path.Combine(snapshot.ProfilePath, RestoreFileName));
                }
                catch (Exception ex)
                {
                    GPAL.PublishSimpleEvent(GPALEventType.EXCEPTION, $"Could not restore the preferences in [{snapshot.ProfilePath}]", null, GPALObjectType.None, ex);
                }
            }
        }

        /// <summary>
        /// Puts the written preferences in one preferences file back. One still holding the value written takes the
        /// value from before, or goes when there was none. One missing now that had a value before gets it back.
        /// Every other line is kept as it is.
        /// </summary>
        /// <param name="path">user.js or prefs.js</param>
        /// <param name="written">The preferences written for the run, and their values</param>
        /// <param name="before">That file's values before the run</param>
        private static void PutBack(string path, Dictionary<string, string> written, Dictionary<string, string> before)
        {
            List<string> lines = new List<string>();
            HashSet<string> present = new HashSet<string>();

            if (true == File.Exists(path))
                foreach (string line in File.ReadAllLines(path))
                {
                    Match match = Regex.Match(line, @"^user_pref\(""([^""]+)"",\s*(.+)\);\s*$");
                    string key = true == match.Success ? match.Groups[1].Value : null;

                    if (null != key)
                        present.Add(key);

                    if (null == key || false == written.TryGetValue(key, out string wrote) || wrote != match.Groups[2].Value.Trim())
                        lines.Add(line);
                    else if (true == before.TryGetValue(key, out string was))
                        lines.Add($"user_pref(\"{key}\", {was});");
                }

            foreach (string key in written.Keys)
                if (false == present.Contains(key) && true == before.TryGetValue(key, out string was))
                    lines.Add($"user_pref(\"{key}\", {was});");

            // A user.js that only ever held what the run wrote goes away with it.
            if (0 == lines.Count(line => 0 < line.Trim().Length))
                File.Delete(path);
            else
                File.WriteAllLines(path, lines);
        }

        /// <summary>
        /// Puts prefs.js back to the values it held before the run, whoever changed them. WebDriver sets its own
        /// automation preferences inside Firefox, not in user.js, and only clears them on a clean shutdown; a killed
        /// run leaves them saved here, and WebDriver never clears a preference that already has a value. A
        /// preference added during the run goes, one changed during the run takes its value from before, and one
        /// removed during the run comes back. <see cref="KeptAfterRun"/> preferences stay as they are.
        /// </summary>
        /// <param name="path">prefs.js</param>
        /// <param name="before">prefs.js values before the run</param>
        private static void RollBack(string path, Dictionary<string, string> before)
        {
            List<string> lines = new List<string>();
            HashSet<string> present = new HashSet<string>();

            if (true == File.Exists(path))
            {
                foreach (string line in File.ReadAllLines(path))
                {
                    Match match = Regex.Match(line, @"^user_pref\(""([^""]+)"",\s*(.+)\);\s*$");
                    string key = true == match.Success ? match.Groups[1].Value : null;

                    if (null == key || true == KeptAfterRun.Contains(key))
                        lines.Add(line);
                    else if (true == before.TryGetValue(key, out string was))
                        lines.Add($"user_pref(\"{key}\", {was});");

                    if (null != key)
                        present.Add(key);
                }

                foreach (KeyValuePair<string, string> preference in before)
                    if (false == present.Contains(preference.Key))
                        lines.Add($"user_pref(\"{preference.Key}\", {preference.Value});");

                File.WriteAllLines(path, lines);
            }
        }

        /// <summary>
        /// Creates a temporary Firefox profile directory under GPAL.WithTempProfileParentDirectory, named like a
        /// Chromium temp profile so one sweep deletes both.
        /// </summary>
        /// <returns>The full path to the created temporary directory.</returns>
        public static string CreateTempProfileDirectory()
        {
            string profilePath = ChromeProfileManager.NewTempProfilePath();

            Directory.CreateDirectory(profilePath);

            return profilePath;
        }
