    /// <summary>
    /// What a supplied Firefox profile held before a run and what the run wrote, so
    /// <see cref="FirefoxProfileManager.RestoreProfile"/> can put it back. Saved in the profile as JSON while the run
    /// lasts, so the public properties are what is written.
    /// </summary>
    internal class FirefoxProfileSnapshot
    {
        // The profile folder; not saved, the folder the file is in says it
        [Newtonsoft.Json.JsonIgnore]
        public string ProfilePath { get; set; }

        // user.js and prefs.js values before the run
        public Dictionary<string, string> UserJsBefore { get; set; } = new Dictionary<string, string>();
        public Dictionary<string, string> PrefsJsBefore { get; set; } = new Dictionary<string, string>();

        // The preferences written for the run, by GPAL or geckodriver, and the values written
        public Dictionary<string, string> Written { get; set; } = new Dictionary<string, string>();
    }
